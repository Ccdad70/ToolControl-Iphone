'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const index=read('index.html'),sw=read('sw.js');
const config=read('tc-iphone-daily-admin-v24.js');
const status=read('tc-iphone-daily-sms-status-v241.js');
const history=read('tc-sms-delivery-history-v25.js');
for(const f of ['tc-iphone-daily-admin-v24.js','tc-iphone-daily-sms-status-v241.js','tc-sms-delivery-history-v25.js'])new vm.Script(read(f),{filename:f});
assert(index.includes('tc-sms-delivery-history-v25.js'));
assert(sw.includes('tc-sms-delivery-history-v25.js'));
assert(sw.includes('toolcontrol-iphone-v250'));
assert(config.includes('canEditMorning()'));
assert(config.includes('tcSmsOwner22?.loaded'));
assert(status.includes("case 'delivered'"));
assert(status.includes('horario configurable'));
assert(history.includes('tc_sms_delivery_history_v25'));
assert(!history.includes('sendTextMessage')&&!history.includes('tc-push'));
assert(!index.includes("tcClient.functions.invoke('tc-push'"));
console.log('OK iPhone V2.5: historial y horario; solo Android envía SMS; sin PUSH');
